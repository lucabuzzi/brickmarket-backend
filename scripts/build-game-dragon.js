// Builds the dragon statue of the plaza ("CardBrix the game") from the artwork.
//   node scripts/build-game-dragon.js
//
// Source: client/brand-src/game/drago_piazza.png (transparent PNG: the dragon standing on its golden disc, blue
// flames included). Output (client/src/assets/game):
//   dragon-statue.png   trimmed and scaled to 3 texture pixels per world unit (the game canvas renders up to 3x)
//   dragon-statue.json  its size in world units and the centre of the golden disc (where the statue stands)
// Used by the plaza scene (lib/game/gameScene.js) and the home-page game card (GamePreviewStage.jsx).
// Does not touch the database, so it does not need scripts/run-db-script.js.
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'client', 'brand-src', 'game', 'drago_piazza.png');
const OUT_DIR = path.join(ROOT, 'client', 'src', 'assets', 'game');

const DISC_WORLD_W = 92; // the golden disc's width on the plaza (the summoning ring under it is 112 wide)
const TEX_PER_WORLD = 3;
const ALPHA_MIN = 40; // fainter pixels are anti-aliasing haze around the artwork

async function main() {
  const { data, info } = await sharp(SRC).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const { width: W, height: H } = info;
  const alpha = (x, y) => data[(y * W + x) * 4 + 3];

  // bounds of the artwork
  let left = W; let right = -1; let top = H; let bottom = -1;
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      if (alpha(x, y) > ALPHA_MIN) {
        if (x < left) left = x; if (x > right) right = x; if (y < top) top = y; if (y > bottom) bottom = y;
      }
    }
  }
  if (right < 0) throw new Error('The dragon image is empty');

  // the golden disc: the widest opaque row in the lower third (wings are higher up)
  let disc = { w: 0, y: 0, x0: 0, x1: 0 };
  for (let y = Math.round(top + (bottom - top) * 0.66); y <= bottom; y++) {
    let a = -1; let z = -1;
    for (let x = left; x <= right; x++) if (alpha(x, y) > 128) { if (a < 0) a = x; z = x; }
    if (a >= 0 && z - a > disc.w) disc = { w: z - a, y, x0: a, x1: z };
  }

  const worldPerSrc = DISC_WORLD_W / disc.w;
  const texW = Math.round((right - left + 1) * worldPerSrc * TEX_PER_WORLD);
  const texH = Math.round((bottom - top + 1) * worldPerSrc * TEX_PER_WORLD);
  fs.mkdirSync(OUT_DIR, { recursive: true });
  await sharp(SRC)
    .extract({ left, top, width: right - left + 1, height: bottom - top + 1 })
    .resize({ width: texW, height: texH, kernel: 'lanczos3' })
    .png({ compressionLevel: 9, palette: true, quality: 90, effort: 10 }) // pixel art: 256 colours are plenty, and the file is far lighter
    .toFile(path.join(OUT_DIR, 'dragon-statue.png'));

  const round = (n) => Math.round(n * 10) / 10;
  const meta = {
    _comment: 'Generated by scripts/build-game-dragon.js. Sizes in world units; (discX, discY) = centre of the golden disc from the top-left corner.',
    texScale: 1 / TEX_PER_WORLD,
    w: round(texW / TEX_PER_WORLD),
    h: round(texH / TEX_PER_WORLD),
    discX: round(((disc.x0 + disc.x1) / 2 - left) * worldPerSrc),
    discY: round((disc.y - top) * worldPerSrc),
    discW: DISC_WORLD_W,
  };
  fs.writeFileSync(path.join(OUT_DIR, 'dragon-statue.json'), `${JSON.stringify(meta, null, 2)}\n`);
  console.log(`dragon-statue.png ${texW}x${texH}`, JSON.stringify(meta));
}

main().catch((err) => { console.error(err); process.exit(1); });
